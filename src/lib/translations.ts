export function translate(text: string, language: Language): string {
  if (language === "en") return text;
  const exact = bengali[text.trim()];
  if (exact) return text.replace(text.trim(), exact);
  const hours = text.trim().match(/^(\d+) hours? ago$/);
  if (hours)
    return text.replace(text.trim(), Number(hours[1]).toLocaleString("bn-BD") + " ঘণ্টা আগে");
  const dynamic: [RegExp, (match: RegExpMatchArray) => string][] = [
    [/^Welcome back, (.+)$/, (m) => "স্বাগতম, " + m[1]],
    [/^Preview (.+)$/, (m) => "প্রিভিউ: " + translate(m[1] ?? "", language)],
    [
      /^(Save|Remove) (.+)$/,
      (m) => (m[1] === "Save" ? "সংরক্ষণ করুন: " : "সরান: ") + translate(m[2] ?? "", language),
    ],
    [/^Select (.+)$/, (m) => "নির্বাচন করুন: " + m[1]],
  ];
  for (const [pattern, format] of dynamic) {
    const match = text.match(pattern);
    if (match) return format(match);
  }
  return text;
}
